def main():
    # 去掉占位行
    persons = [(n, a) for n, a in PERSONS if not n.startswith("#")]
    seen = {}
    mapping = {}
    for i, (name, aliases) in enumerate(persons, start=1):
        pid = "P%03d" % i
        for key in [name] + aliases:
            if key in seen and seen[key] != pid:
                print("COLLISION: %s -> %s and %s" % (key, seen[key], pid), file=sys.stderr)
                return 1
            seen[key] = pid
            mapping[key] = pid
    # 排序输出：按 ID，再按别名
    items = sorted(mapping.items(), key=lambda kv: (kv[1], kv[0]))
    out = {k: v for k, v in items}
    with io.open(OUT, "w", encoding="utf-8") as fh:
        json.dump(out, fh, ensure_ascii=False, indent=1)
    print("alias written: %d 别名 -> %d 人物 -> %s" % (len(out), len(persons), OUT))
    print("关羽 -> %s (必须为 P002)" % mapping.get("关羽"))
    print("云长 -> %s, 美髯公 -> %s" % (mapping.get("云长"), mapping.get("美髯公")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
